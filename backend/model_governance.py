STATES = frozenset({
    "unknown", "healthy", "auth_required", "permission_denied",
    "quota_exhausted", "rate_limited", "model_unavailable", "degraded",
    "unreachable",
})
BLOCKING_STATES = frozenset({
    "auth_required", "quota_exhausted", "permission_denied",
    "model_unavailable",
})
ROUTING_MODES = frozenset({"off", "ask", "auto_within_policy"})
EXPIRY_SOURCES = frozenset({"user_declared", "provider_verified", "unknown"})
_SERVICE: Optional["ModelGovernanceService"] = None


def _now() -> datetime:
    return datetime.now(timezone.utc)


def _iso(value: Optional[datetime] = None) -> str:
    return (value or _now()).astimezone(timezone.utc).isoformat()


def _parse_time(value: Any) -> Optional[datetime]:
    if not value:
        return None
    try:
        parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        return parsed.replace(tzinfo=timezone.utc) if parsed.tzinfo is None else parsed.astimezone(timezone.utc)
    except (TypeError, ValueError):
        return None


def endpoint_fingerprint(endpoint: str) -> str:
    normalized = str(endpoint or "").strip().rstrip("/").casefold()
    return hashlib.sha256(normalized.encode("utf-8")).hexdigest()


def _clean_id(value: Any, *, maximum: int = 200) -> str:
    result = str(value or "").strip()
    if not result or len(result) > maximum or any(ord(char) < 32 for char in result):
        raise ValueError("identifier is invalid")
    return result


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)


def _loads(value: Any, default: Any) -> Any:
    try:
        return json.loads(value) if value else default
    except (TypeError, ValueError):
        return default


def parse_retry_after(value: Any, *, now: Optional[datetime] = None) -> Optional[datetime]:
    text = str(value or "").strip()
    if not text:
        return None
    current = now or _now()
    try:
        seconds = max(0, min(3600, int(float(text))))
        return current + timedelta(seconds=seconds)
    except ValueError:
        try:
            parsed = parsedate_to_datetime(text)
            if parsed.tzinfo is None:
                parsed = parsed.replace(tzinfo=timezone.utc)
            return min(current + timedelta(hours=1), max(current, parsed.astimezone(timezone.utc)))
        except (TypeError, ValueError, OverflowError):
            return None


class GovernanceError(ValueError):
    def __init__(self, code: str, message: str, *, status_code: int = 409, details: Optional[dict[str, Any]] = None):
        super().__init__(message)
        self.code = code
        self.status_code = status_code
        self.details = details or {}


@dataclass(frozen=True)
class GovernanceDecision:
    allowed: bool
    code: str = ""
    message: str = ""
    retry_at: Optional[str] = None
    warnings: tuple[dict[str, Any], ...] = ()
    reservation_id: Optional[str] = None


